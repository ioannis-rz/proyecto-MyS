def simular_periodo(horario: list, ctr=None, cr=None, comision=None) -> dict:
    ctr_    = ctr if ctr is not None else P.CTR
    com     = comision if comision is not None else P.COMISION_UNIT
    cr_vals = list(P.CR_TRACKING.values())

    registros = []
    for dia in range(P.DIAS_SIM):
        dia_semana = dia % 7
        subs       = int(P.SUBS_INICIO * (1 + P.TASA_CRECIMIENTO * dia))
        factor_subs = subs / P.SUBS_INICIO

        lambda_dia_hora = {h: P.LAMBDA_MATRIZ[dia_semana].get(h, 0) for h in horario if P.LAMBDA_MATRIZ[dia_semana].get(h, 0) > 0}

        for hora, lam in lambda_dia_hora.items():
            n_posts_hora = np.random.poisson(lam)
            if n_posts_hora == 0: continue

            v_base  = np.random.lognormal(P.LOGNORM_MU, P.LOGNORM_SIGMA, n_posts_hora)
            v_arr   = np.maximum(1, (v_base * P.FACTOR_HORA[hora] * factor_subs)).astype(int)

            cr_arr  = np.full(n_posts_hora, cr) if cr is not None else np.random.choice(cr_vals, n_posts_hora)
            clics_arr   = np.random.binomial(v_arr, ctr_)
            compras_arr = np.random.binomial(clics_arr, cr_arr)
            comis_arr   = compras_arr * com

            registros.append((v_arr.sum(), clics_arr.sum(), compras_arr.sum(), comis_arr.sum()))

    if not registros: return {'vistas': 0, 'clics': 0, 'compras': 0, 'ctr_real': 0, 'comisiones': 0.0}

    arr = np.array(registros)
    v_tot = arr[:, 0].sum()
    return {
        'vistas': int(v_tot), 'clics': int(arr[:, 1].sum()), 'compras': int(arr[:, 2].sum()),
        'ctr_real': arr[:, 1].sum() / v_tot if v_tot > 0 else 0, 'comisiones': round(arr[:, 3].sum(), 2),
    }

def monte_carlo(horario: list, n: int = None, label: str = '', ctr=None, cr=None) -> pd.DataFrame:
    n = n or P.N_SIMS
    resultados = [simular_periodo(horario, ctr=ctr, cr=cr) for _ in range(n)]
    df = pd.DataFrame(resultados)
    df['sim'] = range(n)
    df['escenario'] = label
    df['media_acum_com'] = df['comisiones'].expanding().mean()
    return df


