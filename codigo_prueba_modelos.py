class MarkovCanal:
    ESTADOS = ['Bajo\n(<3%)', 'Normal\n(3-6%)', 'Alto\n(>6%)']

    def __init__(self, P_mat=None):
        if P_mat is None:
            self.P_mat = np.array([
                [0.50, 0.40, 0.10],
                [0.15, 0.65, 0.20],
                [0.05, 0.35, 0.60],
            ])
        else:
            self.P_mat = P_mat

    @property
    def pi(self):
        n = 3
        A = self.P_mat.T - np.eye(n)
        A[-1, :] = 1.0
        b = np.zeros(n)
        b[-1] = 1.0
        return solve(A, b)

    def freq_acumulada(self, n_dias=600):
        chain = [1]
        for _ in range(n_dias - 1):
            chain.append(np.random.choice(3, p=self.P_mat[chain[-1]]))
        freqs = np.zeros((n_dias, 3))
        for t in range(n_dias):
            for s in range(3):
                freqs[t, s] = (np.array(chain[:t + 1]) == s).mean()
        return freqs

    def print_resumen(self):
        print("\n  MARKOV ERGÓDICO — Estado del Canal")
        print(f"  π = {self.pi}")


